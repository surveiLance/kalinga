export function normalizeInterfaceLanguage(value: unknown): InterfaceLanguage { return value === "fil" || value === "hil" ? value : "en"; }
export function translateInterface(language: InterfaceLanguage, text: string, values: Record<string, string | number> = {}) { const key = text.replace(/\s+/g, " ").trim(); const entry = Object.hasOwn(interfaceTranslations, key) ? interfaceTranslations[key] : undefined; const translated = language === "en" || !entry ? text : entry[language === "fil" ? 0 : 1]; return translated.replace(/\{(\w+)\}/g, (placeholder, name: string) => Object.hasOwn(values, name) ? String(values[name]) : placeholder); }
export function formatInterfaceDate(language: InterfaceLanguage, date: Date) { const parts = new Intl.DateTimeFormat("en-PH", { weekday: "long", month: "long", day: "numeric", year: "numeric" }).formatToParts(date); return parts.map((part) => part.type === "weekday" || part.type === "month" ? translateInterface(language, part.value) : part.value).join(""); }
