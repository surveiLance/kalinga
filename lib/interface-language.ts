let state = serverState, scope = "device";
const listeners = new Set<() => void>();
function publish(language: InterfaceLanguage, persisted = true) { if (state.language === language && state.persisted === persisted) return; state = { language, persisted }; listeners.forEach((listener) => listener()); }
export const readInterfaceLanguage = () => state;
export const serverInterfaceLanguage = () => serverState;
export function subscribeInterfaceLanguage(listener: () => void) { listeners.add(listener); return () => { listeners.delete(listener); }; }
